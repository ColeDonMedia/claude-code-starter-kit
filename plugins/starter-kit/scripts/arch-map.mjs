// Architecture map: ARCHITECTURE.md shows the shape of the codebase at a glance (the areas, how big each is, which depend on which,
// which files everything leans on, and any two areas that depend on each other in a circle). The top part is generated from the
// code index, so it stays true; everything under the "Hand-written" heading is yours and is never touched, for what code cannot
// show (external services, how a request flows at run time, where it is deployed).
// Run: node arch-map.mjs --project <dir> [--write | --check | --print] [--depth N]
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { areas, buildIndex, dependents } from "./code-index.mjs";

const BEGIN = "<!-- arch:begin (generated by arch-map.mjs; do not edit between the markers) -->";
const END = "<!-- arch:end -->";
const HAND = "## Hand-written (external services, how a request flows, where it runs)\n\nWrite here what the code cannot show. This part is never overwritten.\n\n- External services (payments, email, storage, AI) and what each is used for:\n- How a typical request flows through the system:\n- Where it is deployed and how:\n";
const MAX_AREAS = 25;
const MAX_EDGES = 60;

const nodeId = (name) => "n_" + name.replace(/[^A-Za-z0-9]/g, "_");
const anchorOf = (name) => "A-" + name.replace(/\/+$/, "").replace(/[^A-Za-z0-9_.-]/g, "_").replace(/^_+|_+$/g, "");

export function chooseDepth(index) {
  for (const d of [1, 2, 3]) if (areas(index, d).filter((a) => a.area !== "(top level)").length >= 4) return d;
  return 3;
}

export function buildArch(index, depth = chooseDepth(index)) {
  const all = areas(index, depth);
  const shown = all.slice(0, MAX_AREAS);
  const names = new Set(shown.map((a) => a.area));
  const areaOf = (f) => {
    const parts = f.split("/");
    return parts.length > depth ? parts.slice(0, depth).join("/") + "/" : "(top level)";
  };
  const edges = new Map();
  for (const [f, e] of Object.entries(index.files)) for (const d of e.deps ?? []) {
    const a = areaOf(f);
    const b = areaOf(d);
    if (a === b || !names.has(a) || !names.has(b)) continue;
    const k = `${a}\0${b}`;
    edges.set(k, (edges.get(k) ?? 0) + 1);
  }
  const list = [...edges.entries()].map(([k, n]) => ({ from: k.split("\0")[0], to: k.split("\0")[1], n })).sort((x, y) => y.n - x.n || x.from.localeCompare(y.from) || x.to.localeCompare(y.to)).slice(0, MAX_EDGES);
  const mutual = [];
  for (const e of list) if (e.from < e.to && list.some((o) => o.from === e.to && o.to === e.from)) mutual.push([e.from, e.to]);
  const rev = dependents(index);
  const hubs = [...rev.entries()].map(([file, s]) => ({ file, n: s.size })).sort((a, b) => b.n - a.n || a.file.localeCompare(b.file)).slice(0, 10);
  return { shown, hiddenAreas: all.length - shown.length, edges: list, mutual, hubs, depth };
}

export function render(arch) {
  const L = [BEGIN, "", "# Architecture", "", `${arch.shown.length} area(s) shown${arch.hiddenAreas ? ` (${arch.hiddenAreas} smaller ones left out)` : ""}, grouped by folder ${arch.depth} level(s) deep. Generated from the code index: dynamic imports and generated code are not seen.`, "", "## Diagram", "", "```mermaid", "flowchart LR"];
  const n = (k, w) => `${k} ${w}${k === 1 ? "" : "s"}`;
  for (const a of arch.shown) L.push(`  ${nodeId(a.area)}["${a.area.replace(/"/g, "")}<br/>${n(a.files, "file")}"]`);
  for (const e of arch.edges) L.push(`  ${nodeId(e.from)} -->|${e.n}| ${nodeId(e.to)}`);
  L.push("```", "", "## Areas", "");
  for (const a of arch.shown) {
    const out = arch.edges.filter((e) => e.from === a.area);
    const inn = arch.edges.filter((e) => e.to === a.area);
    const name = (n) => `[[${anchorOf(n)}]]`;
    L.push(`### ${a.area} {#${anchorOf(a.area)}}`, "", `${n(a.files, "file")}, ${n(a.lines, "line")} (${a.langs.join(", ")}).`);
    L.push(`Depends on: ${out.length ? out.map((e) => `${name(e.to)} (${e.n})`).join(", ") : "nothing else shown"}.`);
    L.push(`Used by: ${inn.length ? inn.map((e) => `${name(e.from)} (${e.n})`).join(", ") : "nothing else shown"}.`, "");
  }
  L.push("## What everything leans on", "", "Files the most other files import. Change these with the most care.", "");
  if (arch.hubs.length) for (const h of arch.hubs) L.push(`- ${h.file} (${h.n} dependents)`);
  else L.push("- none found");
  L.push("", "## Circular dependencies between areas", "");
  if (arch.mutual.length) for (const [a, b] of arch.mutual) L.push(`- ${a} and ${b} depend on each other: hard to change either alone`);
  else L.push("- none found between the areas shown");
  L.push("", END);
  return L.join("\n");
}

export function archStatus(root, depth) {
  const { index } = buildIndex(root);
  if (!Object.keys(index.files).length) return { state: "none" };
  const block = render(buildArch(index, depth));
  const p = join(root, "ARCHITECTURE.md");
  const cur = existsSync(p) ? readFileSync(p, "utf8").replace(/\r/g, "") : null;
  const curBlock = cur && cur.includes(BEGIN) && cur.includes(END) ? cur.slice(cur.indexOf(BEGIN), cur.indexOf(END) + END.length) : null;
  const hand = cur && cur.includes(END) ? cur.slice(cur.indexOf(END) + END.length).replace(/^\n+/, "") : HAND;
  return { state: cur === null ? "missing" : curBlock === block ? "current" : "stale", block, text: `${block}\n\n${hand.replace(/\n*$/, "\n")}` };
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  const a = process.argv.slice(2);
  const get = (f) => (a.includes(f) ? a[a.indexOf(f) + 1] : undefined);
  const root = resolve(get("--project") ?? ".");
  const st = archStatus(root, get("--depth") ? Number(get("--depth")) : undefined);
  if (st.state === "none") console.log("No source files found to map.");
  else if (a.includes("--write")) {
    writeFileSync(join(root, "ARCHITECTURE.md"), st.text);
    console.log("ARCHITECTURE.md written (your hand-written part, if any, was kept).");
  } else if (a.includes("--print")) console.log(st.text);
  else {
    console.log(st.state === "current" ? "ARCHITECTURE.md is current." : `ARCHITECTURE.md is ${st.state}: run arch-map.mjs --write.`);
    process.exitCode = st.state === "current" ? 0 : 1;
  }
}
